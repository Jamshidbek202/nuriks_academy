def set_cell_shading(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = tc_pr.find(qn("w:shd"))
    if shd is None:
        shd = OxmlElement("w:shd")
        tc_pr.append(shd)
    shd.set(qn("w:fill"), fill)


def set_cell_border(cell, color="B8C9D9", size="8"):
    tc_pr = cell._tc.get_or_add_tcPr()
    borders = tc_pr.first_child_found_in("w:tcBorders")
    if borders is None:
        borders = OxmlElement("w:tcBorders")
        tc_pr.append(borders)
    for edge in ("top", "left", "bottom", "right"):
        tag = "w:" + edge
        element = borders.find(qn(tag))
        if element is None:
            element = OxmlElement(tag)
            borders.append(element)
        element.set(qn("w:val"), "single")
        element.set(qn("w:sz"), size)
        element.set(qn("w:color"), color)


def set_repeat_table_header(row):
    tr_pr = row._tr.get_or_add_trPr()
    tbl_header = OxmlElement("w:tblHeader")
    tbl_header.set(qn("w:val"), "true")
    tr_pr.append(tbl_header)


def set_row_cant_split(row):
    tr_pr = row._tr.get_or_add_trPr()
    cant_split = OxmlElement("w:cantSplit")
    tr_pr.append(cant_split)


def set_keep_with_next(paragraph):
    paragraph.paragraph_format.keep_with_next = True


def add_label_paragraph(cell, label, text, fill):
    set_cell_shading(cell, fill)
    set_cell_border(cell)
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    p = cell.paragraphs[0]
    p.paragraph_format.space_after = Pt(0)
    run = p.add_run(label)
    run.bold = True
    run.font.color.rgb = RGBColor.from_string(NAVY)
    p.add_run(text)


def add_question(doc, number, title, why, recommendation, answer_lines=4):
    heading = doc.add_paragraph()
    heading.style = doc.styles["Heading 2"]
    heading.paragraph_format.space_before = Pt(10)
    heading.paragraph_format.space_after = Pt(5)
    set_keep_with_next(heading)
    run = heading.add_run(f"{number}. {title}")
    run.font.color.rgb = RGBColor.from_string(BLUE)

    table = doc.add_table(rows=2, cols=1)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.autofit = True
    add_label_paragraph(table.cell(0, 0), "Почему нужно уточнить: ", why, LIGHT_GREY)
    add_label_paragraph(table.cell(1, 0), "Рекомендуемый вариант: ", recommendation, LIGHT_BLUE)
    for row in table.rows:
        set_row_cant_split(row)

    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(5)
    p.paragraph_format.space_after = Pt(2)
    set_keep_with_next(p)
    r = p.add_run("Согласованное решение")
    r.bold = True
    r.font.color.rgb = RGBColor.from_string(NAVY)

    answer = doc.add_table(rows=1, cols=1)
    answer.alignment = WD_TABLE_ALIGNMENT.CENTER
    cell = answer.cell(0, 0)
    set_cell_border(cell, color="9FBAD0", size="10")
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.TOP
    cell.paragraphs[0].add_run("\n" * answer_lines)
    set_row_cant_split(answer.rows[0])


